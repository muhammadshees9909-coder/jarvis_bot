
lines = []

# Set mode
lines.append("")
lines.append("function setMode(docked) {")
lines.append("  STATE.docked = docked;")
lines.append("  if (docked) {")
lines.append('    STATE.card.style.bottom = "0";')
lines.append('    STATE.card.style.right = "0";')
lines.append('    STATE.card.style.left = "0";')
lines.append('    STATE.card.style.width = "100%";')
lines.append('    STATE.card.style.height = "100%";')
lines.append('    STATE.card.style.minHeight = "auto";')
lines.append('    STATE.card.style.borderRadius = "0";')
lines.append('    STATE.card.style.boxShadow = "none";')
lines.append('    STATE.bubble.style.bottom = "16px";')
lines.append('    STATE.bubble.style.right = "16px";')
lines.append('    STATE.hint.textContent = "JARVIS is docked as a full side panel. Click the bubble to hide it.";')
lines.append("  } else {")
lines.append('    STATE.card.style.bottom = "calc(var(--bubble-gap) + var(--bubble-size) + var(--bubble-gap))";')
lines.append('    STATE.card.style.right = "var(--bubble-gap)";')
lines.append('    STATE.card.style.left = "auto";')
lines.append('    STATE.card.style.width = "var(--card-width)";')
lines.append('    STATE.card.style.height = "auto";')
lines.append('    STATE.card.style.minHeight = "var(--card-min-height)";')
lines.append('    STATE.card.style.borderRadius = "var(--radius-lg)";')
lines.append('    STATE.card.style.boxShadow = "var(--glass-shadow-lg)";')
lines.append('    STATE.bubble.style.bottom = "var(--bubble-gap)";')
lines.append('    STATE.bubble.style.right = "var(--bubble-gap)";')
lines.append('    STATE.hint.textContent = "Tip: dock as a side panel for a full conversation window. Click the card header to collapse.";')
lines.append("  }")
lines.append("  requestAnimationFrame(function() {")
lines.append("    if (!STATE.docked && STATE.open) {")
lines.append("      STATE.card.classList.remove('closed');")
lines.append('      STATE.card.style.opacity = "1";')
lines.append('      STATE.card.style.transform = "scale(1) translateY(0)";')
lines.append("    } else if (STATE.docked) {")
lines.append('      STATE.card.style.opacity = "1";')
lines.append('      STATE.card.style.transform = "scale(1) translateY(0)";')
lines.append("    }")
lines.append("  });")
lines.append("}")

# Bind events
lines.append("")
lines.append("function bindEvents() {")
lines.append("  STATE.bubble.addEventListener('click', function() {")
lines.append("    if (STATE.docked) {")
lines.append("      STATE.card.classList.add('closed');")
lines.append('      STATE.card.style.opacity = "0";')
lines.append('      STATE.card.style.transform = "scale(1) translateY(100%)";')
lines.append('      STATE.bubble.style.display = "flex";')
lines.append("    } else {")
lines.append("      STATE.open ? closeCard() : openCard();")
lines.append("    }")
lines.append("  });")
lines.append("")
lines.append("  STATE.card.addEventListener('click', function(e) {")
lines.append("    if (e.target.closest('#jarvis-card')) return;")
lines.append("    if (!STATE.docked && STATE.open) closeCard();")
lines.append("  });")
lines.append("")
lines.append("  STATE.btnFloat.addEventListener('click', function() { if (STATE.docked) setMode(false); });")
lines.append("  STATE.btnSide.addEventListener('click', function() { if (!STATE.docked) setMode(true); });")
lines.append("  STATE.btnBack.addEventListener('click', function() {")
lines.append("    if (STATE.docked) setMode(false);")
lines.append("    else if (STATE.open) closeCard();")
lines.append("  });")
lines.append("")
lines.append("  STATE.quickRepl.addEventListener('click', function() {")
lines.append("    if (STATE.open && !STATE.docked) closeCard();")
lines.append("  });")
lines.append("")
lines.append("  STATE.sendBtn.addEventListener('click', sendMessage);")
lines.append("")
lines.append("  STATE.textarea.addEventListener('keydown', function(e) {")
lines.append("    if (e.key === 'Enter' && !e.shiftKey) {")
lines.append("      e.preventDefault();")
lines.append("      sendMessage();")
lines.append("    }")
lines.append("  });")
lines.append("")
lines.append("  STATE.textarea.addEventListener('input', function() {")
lines.append('    STATE.textarea.style.height = "auto";')
lines.append('    STATE.textarea.style.height = Math.min(STATE.textarea.scrollHeight, 120) + "px";')
lines.append("  });")
lines.append("}")

with open(r"c:/jarvis-bot/extension/part5.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
