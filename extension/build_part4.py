
lines = []

# sendMessage
lines.append("")
lines.append("async function sendMessage() {")
lines.append("  const text = STATE.textarea.value.trim();")
lines.append("  if (!text || STATE.submitting) return;")
lines.append("  STATE.messageId += 1;")
lines.append("")
lines.append("  const userEl = document.createElement('div');")
lines.append('  userEl.className = "jarvis-message jarvis-user";')
lines.append("  userEl.textContent = text;")
lines.append("  STATE.messages.appendChild(userEl);")
lines.append("  STATE.messages.scrollTop = STATE.messages.scrollHeight;")
lines.append("")
lines.append("  STATE.textarea.value = '';")
lines.append("  STATE.textarea.dispatchEvent(new Event('input'));")
lines.append("  setLoading(true);")
lines.append('  STATE.btnSend.style.opacity = "0.5";')
lines.append('  STATE.btnSend.style.cursor = "default";')
lines.append("")
lines.append("  try {")
lines.append("    const payload = {")
lines.append("      message: text,")
lines.append("      session_id: STATE.sessionId")
lines.append("    };")
lines.append("    const data = await chatFetch(payload);")
lines.append("    STATE.sessionId = data.session_id || STATE.sessionId;")
lines.append("")
lines.append("    if (data.error) {")
lines.append("      showError(data.error);")
lines.append("    } else {")
lines.append("      renderResponse(data.response);")
lines.append("    }")
lines.append("    renderQuickReplies(data.quick_replies || data.quickReplies || []);")
lines.append("  } catch (err) {")
lines.append('    showError("Request failed: " + err.message);')
lines.append("  } finally {")
lines.append("    setLoading(false);")
lines.append('    STATE.btnSend.style.opacity = "1";')
lines.append('    STATE.btnSend.style.cursor = "pointer";')
lines.append("  }")
lines.append("}")

# Open card
lines.append("")
lines.append("function openCard() {")
lines.append("  if (STATE.docked || STATE.open) return;")
lines.append("  STATE.open = true;")
lines.append("  STATE.card.classList.remove('closed');")
lines.append('  STATE.card.style.opacity = "1";')
lines.append('  STATE.card.style.transform = "scale(1) translateY(0)";')
lines.append('  STATE.bubble.style.display = "none";')
lines.append("  setTimeout(function() { STATE.textarea.focus(); }, 100);")
lines.append("}")

# Close card
lines.append("")
lines.append("function closeCard() {")
lines.append("  if (!STATE.open) return;")
lines.append("  STATE.open = false;")
lines.append("  STATE.card.classList.add('closed');")
lines.append('  STATE.card.style.opacity = "0";')
lines.append('  STATE.card.style.transform = "scale(0.88) translateY(20px)";')
lines.append('  STATE.bubble.style.display = "flex";')
lines.append("}")

with open(r"c:/jarvis-bot/extension/part4.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
